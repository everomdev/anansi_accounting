<?php
$this->registerJs("
$('#user-password').click(function(e) {
    var field = $(this);
    var rect = this.getBoundingClientRect();
    var clickX = e.clientX - rect.left;
    var fieldWidth = rect.width;
    
    // Si hace clic en los últimos 35px (donde está el ícono)
    if (clickX >= fieldWidth - 35) {
        if (field.attr('type') === 'password') {
            field.attr('type', 'text');
            field.addClass('show-password');
        } else {
            field.attr('type', 'password');
            field.removeClass('show-password');
        }
        e.preventDefault();
    }
});

// Cambiar cursor solo en la zona del ícono
$('#user-password').mousemove(function(e) {
    var rect = this.getBoundingClientRect();
    var clickX = e.clientX - rect.left;
    var fieldWidth = rect.width;
    
    if (clickX >= fieldWidth - 35) {
        $(this).css('cursor', 'pointer');
    } else {
        $(this).css('cursor', 'text');
    }
});
");
